const supportedRoomLanguages = ["es", "en", "fr"];
const savedRoomLanguage = localStorage.getItem("natura54Language");
let roomLanguage = supportedRoomLanguages.includes(savedRoomLanguage) ? savedRoomLanguage : "es";
let roomCopy = roomTranslations[roomLanguage];

function applyRoomLanguage() {
  roomCopy = roomTranslations[roomLanguage];
  document.documentElement.lang = roomLanguage;
  document.title = `${roomCopy.roomsLabel} | Natura 54 Experience`;

  document.querySelectorAll("[data-room-i18n]").forEach((node) => {
    const key = node.dataset.roomI18n;
    node.textContent = roomCopy[key];
  });

  document.querySelectorAll("[data-room-aria]").forEach((node) => {
    const key = node.dataset.roomAria;
    node.setAttribute("aria-label", roomCopy[key]);
  });

  document.querySelectorAll(".amenities").forEach((section) => {
    const roomNumber = section.getAttribute("aria-label")?.match(/\d+/)?.[0];
    section.setAttribute("aria-label", `${roomCopy.amenitiesTitle} ${roomCopy.roomLabel.toLowerCase()} ${roomNumber || ""}`.trim());
  });

  document.querySelectorAll(".room-carousel").forEach((carousel) => {
    const roomNumber = carousel.getAttribute("aria-label")?.match(/\d+/)?.[0];
    carousel.setAttribute("aria-label", `${roomCopy.roomsLabel} ${roomNumber || ""}`.trim());
  });

  document.querySelectorAll(".airbnb-link, .booking-link").forEach((link) => {
    const roomNumber = link.getAttribute("aria-label")?.match(/\d+/)?.[0];
    const platform = link.classList.contains("airbnb-link") ? "Airbnb" : "Booking";
    link.setAttribute("aria-label", `${roomCopy.roomLabel} ${roomNumber || ""} ${platform}`.trim());
  });

  if (roomsLanguagePill) {
    roomsLanguagePill.textContent = roomLanguage.toUpperCase();
    roomsLanguagePill.setAttribute("aria-label", `${roomCopy.back === "Back" ? "Change language" : roomCopy.back === "Retour" ? "Changer de langue" : "Cambiar idioma"}`);
  }
}

const roomsLanguagePill = document.querySelector("#roomsLanguagePill");
const backToGuide = document.querySelector("[data-room-aria='back']");

if (roomsLanguagePill) {
  roomsLanguagePill.addEventListener("click", () => {
    const currentIndex = supportedRoomLanguages.indexOf(roomLanguage);
    roomLanguage = supportedRoomLanguages[(currentIndex + 1) % supportedRoomLanguages.length];
    localStorage.setItem("natura54Language", roomLanguage);
    sessionStorage.setItem("natura54GuideActive", "true");
    applyRoomLanguage();
  });
}

if (backToGuide) {
  backToGuide.addEventListener("click", () => {
    sessionStorage.setItem("natura54GuideActive", "true");
  });
}

sessionStorage.setItem("natura54GuideActive", "true");
applyRoomLanguage();
